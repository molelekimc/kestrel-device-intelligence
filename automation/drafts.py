"""Briefing files: YAML front matter, the briefing body, and a code-generated evidence appendix."""

from pathlib import Path

import yaml

from pipeline.config import ROOT

BRIEFINGS = ROOT / "briefings"
APPENDIX_MARK = "<!-- evidence appendix: generated by code, not by the model -->"


def drafts_dir() -> Path:
    return BRIEFINGS / "drafts"


def approved_dir() -> Path:
    return BRIEFINGS / "approved"


def save(path: Path, meta: dict, body: str, appendix: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    front = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True)
    path.write_text(f"---\n{front}---\n\n{body.strip()}\n\n{APPENDIX_MARK}\n\n{appendix.strip()}\n")


def load(path: Path) -> tuple[dict, str, str]:
    text = Path(path).read_text()
    if not text.startswith("---\n"):
        raise ValueError(f"{path} has no front matter")
    _, front, rest = text.split("---\n", 2)
    body, _, appendix = rest.partition(APPENDIX_MARK)
    return yaml.safe_load(front), body.strip(), appendix.strip()
